// Универсальный обработчик для /api/chat и /api/message
const handleSchoolChat = async (req, res) => {
  const message = req.body?.message || req.body?.text;

  if (!message) {
    return res.status(400).json({ error: 'Сообщение не может быть пустым' });
  }

  try {
    const response = await fetch('https://openrouter.ai/api/v1/chat/completions', {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${process.env.OPENROUTER_API_KEY}`,
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        model: 'qwen/qwen-2.5-coder-32b-instruct',
        messages: [
          { role: 'system', content: SCHOOL_KNOWLEDGE_BASE },
          { role: 'user', content: message }
        ]
      })
    });

    const data = await response.json();
    const reply = data.choices?.[0]?.message?.content || 'Не удалось получить ответ от системы школы № 1770.';

    // Отдаем ответ сразу во всех ключах для полной совместимости с фронтендом
    res.json({ reply: reply, answer: reply });
  } catch (error) {
    console.error('Ошибка сервера:', error);
    res.status(500).json({ reply: 'Произошла ошибка при обращении к серверу школы № 1770.' });
  }
};

app.post('/api/chat', handleSchoolChat);
app.post('/api/message', handleSchoolChat);

const PORT = process.env.PORT || 3000;
